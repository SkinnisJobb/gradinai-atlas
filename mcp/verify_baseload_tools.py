"""Prove every MCP tool atlas-mcp registers has its baseload node (STORY-oss-23, check C2).

The baseload (`backend/baseload_data.py`, generated by `tools/gen_baseload.py`) describes each tool
as a node `atlas-system-tool-<name>` under its group node (agent/plans/oss-baseload.md section 3.4).
This script imports the real `app.mcp_server` (a stub env, no network), reads the tool list off the
live FastMCP registry with BOTH conditional tools registered (`ATLAS_MCP_ENABLE_DELETE` set, no
feature disabled), and checks:

  A. the set of registered tools is exactly the set of tools the baseload's tool nodes name, each
     node's id is `atlas-system-tool-` plus the name, it sits under a group node that lists it,
     and its summary is the start of the tool's description; so a NEW TOOL WITHOUT A NODE FAILS
     HERE, and C1 (`gen_baseload.py --check`) fails until the module is regenerated.
  B. the check can fail: a dummy tool registered on the same server makes it red, and the
     dummy is named in the difference.

Under decision D-B6 = per_group (tools/baseload/authored.json) there are no tool nodes; then the
union of the group nodes' `attributes.baseload.tools` must equal the registry instead.

The baseload module is read as data (`ast.literal_eval` of its assignments), never imported, so
this needs nothing from the backend.

    python mcp/verify_baseload_tools.py
"""

import ast
import asyncio
import os
import sys
import warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "backend" / "baseload_data.py"

for _name in [n for n in os.environ if n.startswith("ATLAS_")]:
    del os.environ[_name]
os.environ["ATLAS_BASE_URL"] = "https://atlas.invalid"
os.environ["ATLAS_MCP_ENABLE_DELETE"] = "1"
sys.path.insert(0, str(HERE))

import httpx  # noqa: E402


def _refuse(*_a, **_k):
    raise RuntimeError("verify_baseload_tools: registering the tools must not make a network call")


httpx.Client.request = _refuse
httpx.AsyncClient.request = _refuse

failures: list = []


def check(label: str, condition: bool, detail: str = "") -> None:
    print(f"[{'PASS' if condition else 'FAIL'}] {label}" + (f" — {detail}" if detail else ""))
    if not condition:
        failures.append(label)


def load_nodes() -> list:
    for stmt in ast.parse(DATA.read_text(encoding="utf-8")).body:
        if isinstance(stmt, ast.Assign) and [getattr(t, "id", None) for t in stmt.targets] == ["NODES"]:
            return ast.literal_eval(stmt.value)
    raise SystemExit(f"{DATA}: no NODES assignment")


def tool_id(name: str) -> str:
    return "atlas-system-tool-" + name.removeprefix("atlas_").replace("_", "-")


def mismatch(registered: set, nodes: list) -> list:
    """Every reason the baseload does not describe exactly `registered`. Empty: it does."""
    probs = []
    tools = {n["attributes"]["baseload"]["tool"]: n for n in nodes
             if "tool" in n["attributes"].get("baseload", {})}
    groups = {n["id"]: n for n in nodes if "tools" in n["attributes"].get("baseload", {})}
    if tools:
        for name in sorted(registered - set(tools)):
            probs.append(f"registered tool {name} has no baseload node ({tool_id(name)}); "
                         "run `python tools/gen_baseload.py` and commit backend/baseload_data.py")
        for name in sorted(set(tools) - registered):
            probs.append(f"baseload node {tools[name]['id']} names {name}, which is not registered")
        for name, n in sorted(tools.items()):
            if n["id"] != tool_id(name):
                probs.append(f"{n['id']}: the id of tool {name} must be {tool_id(name)}")
            g = groups.get(n["parent"])
            if g is None or name not in g["attributes"]["baseload"]["tools"]:
                probs.append(f"{n['id']}: its parent {n['parent']} is not a group node listing it")
    else:
        listed = {t for g in groups.values() for t in g["attributes"]["baseload"]["tools"]}
        probs += [f"registered tool {t} is in no group node" for t in sorted(registered - listed)]
        probs += [f"a group node lists {t}, which is not registered" for t in sorted(listed - registered)]
    return probs


with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    from app import mcp_server  # noqa: E402

registry = asyncio.run(mcp_server.mcp.list_tools())
registered = {t.name for t in registry}
nodes = load_nodes()

print("=" * 78)
print("A. every registered tool has its baseload node, and nothing more")
print("=" * 78)
check("both conditional tools are registered here (atlas_delete, atlas_save_work)",
      {"atlas_delete", "atlas_save_work"} <= registered, str(sorted(registered))[:200])
probs = mismatch(registered, nodes)
check(f"the {len(registered)} registered tools are exactly the baseload's tool nodes", not probs,
      "; ".join(probs[:4]))
by_tool = {n["attributes"]["baseload"]["tool"]: n for n in nodes if "tool" in n["attributes"].get("baseload", {})}
desc = {t.name: " ".join((t.description or "").split()) for t in registry}
check("each tool node's summary is the start of the tool's description",
      all(desc.get(k, "").startswith(n["summary"].rstrip(".?!")[:40]) for k, n in by_tool.items()),
      str([k for k, n in by_tool.items() if not desc.get(k, "").startswith(n["summary"].rstrip(".?!")[:40])]))

print("=" * 78)
print("B. the check can fail: a dummy tool without a node")
print("=" * 78)


def atlas_baseload_dummy() -> dict:
    return {}


mcp_server.mcp.tool(description="Dummy tool registered by verify_baseload_tools.py.")(atlas_baseload_dummy)
after = {t.name for t in asyncio.run(mcp_server.mcp.list_tools())}
red = mismatch(after, nodes)
check("the dummy tool is registered", "atlas_baseload_dummy" in after)
check("and the check is red, naming it", bool(red) and any("atlas_baseload_dummy" in p for p in red),
      "; ".join(red[:2]))

print("=" * 78)
if failures:
    print(f"{len(failures)} FAILED:")
    for f in failures:
        print(f"  - {f}")
    sys.exit(1)
print("ALL PASSED")
