"""`/docs`: the Atlas handbook as a static site (STORY-atlas-system-node-handbook).

The pages are `frontend/docs/`, generated by `tools/docs_site.py` from the same documents the
`atlas-system` node set carries (`system_handbook.py`); this router only serves those files.

WHAT IS SERVED. Exactly the names in `system_handbook.SITE_FILES`, matched as whole strings,
the way `ASSET_FILES` works: no directory walk, no mount, and a `..` segment is only ever a
dict miss. `/docs` and `/docs/` are the index. Nothing here touches the database.

WHO MAY READ IT. Behind the gate, like every route, unless `ATLAS_PUBLIC_DOCS=1`: then
`auth.PUBLIC_ROUTES` gains these exact paths (`system_handbook.public_paths()`) and nothing
else. Why that is safe is argued where the paths are added, in `auth.py` §2. Every response
is `private, no-cache` whichever way it is configured: when the site is gated, a shared cache
storing an authenticated page is the 2026-08-18 `board.css` incident (`routers/assets.py`);
when it is public there is nothing to lose by revalidating. The pages carry their own
Content-Security-Policy too, so a deployment without the OSS ingress's header still runs them
with no script at all.
"""
from __future__ import annotations

import os

from fastapi import APIRouter
from fastapi.responses import FileResponse, JSONResponse, Response

import system_handbook
from deps import FRONTEND

router = APIRouter()

SITE_FILES = frozenset(system_handbook.SITE_FILES)
DOCS_HEADERS = {
    "Cache-Control": "private, no-cache",
    "Content-Security-Policy": ("default-src 'none'; style-src 'self'; img-src 'self'; "
                                "base-uri 'none'; form-action 'none'; frame-ancestors 'none'"),
    "X-Content-Type-Options": "nosniff",
}


def _site_file(name: str) -> Response:
    if name not in SITE_FILES:
        return JSONResponse({"error": "not found"}, status_code=404)
    full = os.path.join(FRONTEND, "docs", *name.split("/"))
    if not os.path.isfile(full):
        return JSONResponse({"error": "not found"}, status_code=404)
    return FileResponse(full, headers=DOCS_HEADERS)


@router.get("/docs")
def handbook_index() -> Response:
    return _site_file("index.html")


@router.get("/docs/{name:path}")
def handbook_file(name: str) -> Response:
    return _site_file(name or "index.html")
