"""
Verification for the baseload (STORY-oss-23, agent/plans/oss-baseload.md check C3): the world model
a fresh install ships with, `baseload_data.py`, generated by `tools/gen_baseload.py` and seeded by
`system_node.py` after the handbook set.

  A. the data, without a database: every id starts `atlas-system`, no id twice, every node has a
     summary and a parent earlier in the set, no edge or intent dangles, every `requires` edge is
     object -> object; the set covers the code it was generated from: every router module the
     live route table declares (every route-adding switch on), every `frontend/v2/views/` entry,
     every panel tab in `TABS`, every `deploy/oss/docker-compose.yml` service; and the
     forbidden patterns (C5) find nothing in it.
  B. a fresh database under each profile that seeds the system set (none, demo, self) gets the
     handbook set plus exactly the baseload: nodes, `contains` and `requires` edges, documents
     listed in `docs[]`, intents, no graph_event; no `edge_type_warnings()` about its edges and
     no `name_register_warnings()` for any node of the set (decision D-B2: `node_types` skips
     generated nodes, whose identifier names come from the code; a perturbation proves every
     other node is still reported); a second boot writes nothing ("boot is a read").
  C. `homelab` seeds none of it, and a populated database is not touched at boot under any profile.
  D. an install that has only the seven handbook nodes runs `system_node.py --apply` and gets the
     rest; nothing that existed changes, and a person's own node holding a baseload id is never
     wired in (no edge to or from it, its row byte-identical).

What it cannot run: `tools/gen_baseload.py --check` (C1) needs the mcp requirements too, and runs
in scrub.yml's docs-freshness step; `mcp/verify_baseload_tools.py` (C2) is the MCP half.

Every boot is a separate process (`import app; app.startup()`), as in verify_system_node.py.

Run:
    python verify_baseload.py
"""
