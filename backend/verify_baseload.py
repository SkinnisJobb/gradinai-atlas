def check(label: str, condition: bool, detail: str = "") -> None:
    print(f"[{'PASS' if condition else 'FAIL'}] {label}" + (f" — {detail}" if detail else ""))
    if not condition:
        failures.append(label)


def run_child(args: list[str], env: dict[str, str] | None = None, stdin: str | None = None) -> subprocess.CompletedProcess:
    child_env = dict(BASE_ENV)
    child_env.update(env or {})
    proc = subprocess.run([sys.executable, *args], cwd=HERE, env=child_env, input=stdin,
                          capture_output=True, text=True, timeout=300)
    if proc.returncode != 0:
        print(f"  child {args[:2]!r} env={env} exited {proc.returncode}")
        print("  stdout: " + proc.stdout[-1500:].replace("\n", "\n  "))
        print("  stderr: " + proc.stderr[-1500:].replace("\n", "\n  "))
    return proc


def boot(env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    return run_child(["-c", "import app; app.startup()"], env)


#: STORY-oss-23 A3b: whether the distribution's DEFAULT profile seeds the system set on a fresh
#: graph. The homelab copy defaults to `homelab`, which never does; the neutral copy's every
#: profile does. Sections C and D need an install WITHOUT the set (one made before it existed):
#: under the homelab copy that is the default boot, exactly as before; otherwise it is a boot
#: with `system_node.seed` stubbed out in that one child process, so startup is otherwise real.
DEFAULT_SEEDS_SET = distribution.DEFAULT_SEED_PROFILE != "homelab"
BOOT_WITHOUT_SET = ("import system_node\n"
                    "system_node.seed = lambda s: []  # an install made before the set existed\n"
                    "import app\napp.startup()")


def boot_without_set(homelab_env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    """A boot that leaves no system set: `homelab_env` under the homelab copy (as before), else
    the default profile with the set's seeding stubbed out (see DEFAULT_SEEDS_SET)."""
    if not DEFAULT_SEEDS_SET:
        return boot(homelab_env)
    return run_child(["-c", BOOT_WITHOUT_SET], {})


def child_json(script: str, tag: str, env: dict | None = None) -> dict:
    proc = run_child(["-c", script], env)
    line = next((ln for ln in proc.stdout.splitlines() if ln.startswith(tag + " ")), None)
    return json.loads(line[len(tag) + 1:]) if line else {}


def reset() -> None:
    with ENGINE.begin() as conn:
        conn.execute(text("DROP SCHEMA public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))


def rows(sql: str, **params) -> list[tuple]:
    with ENGINE.connect() as conn:
        return [tuple(r) for r in conn.execute(text(sql), params)]


def data() -> dict[str, tuple]:
    """(row count, sha256 of every row) per table, plus every sequence position."""
    out: dict[str, tuple] = {}
    with ENGINE.connect() as conn:
        for t in sorted(r[0] for r in conn.execute(text(
                "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"))):
            # SQLAlchemy Core quotes the table name; no SQL string is assembled (as in
            # verify_guardrails.data()).
            got = sorted(r for (r,) in conn.execute(
                select(cast(func.to_jsonb(literal_column("t")), Text)).select_from(table(t).alias("t"))))
            out[t] = (len(got), hashlib.sha256("\n".join(got).encode("utf-8")).hexdigest())
        for name, last in conn.execute(text(
                "SELECT sequencename, last_value FROM pg_sequences WHERE schemaname = 'public'")):
            out[f"sequence:{name}"] = (-1, str(last))
    return out


def system_ids() -> list[str]:
    return [r[0] for r in rows("SELECT id FROM node WHERE id LIKE 'atlas-system%' ORDER BY id")]


