"""The Atlas system node, its handbook and the baseload (STORY-atlas-system-node-handbook, STORY-oss-23).

Every install can describe itself: a `system` node `atlas-system` with one child per part
(`atlas-system-api`, `-mcp`, `-postgres`, `-gateway`, `-search`, `-retrieval`), whose node
documents are the handbook. The data is `system_handbook.py` (hand-written Python data, like
`demo_seed.py`); `tools/docs_site.py` renders the same data into the static
`/docs` site, so the board, an agent's `atlas_doc_read` and `/docs` read one text.

THE BASELOAD (agent/plans/oss-baseload.md) extends that set into the world model of the product:
the compose services, the capability areas, every MCP tool, every API area, the board's views and
the admin CLI, with their `requires` edges, documents and the intents that ship. The data is
`baseload_data.py`, GENERATED by `tools/gen_baseload.py` from the code; it is seeded after the
handbook nodes, under the same rules. The handbook nodes keep their ids, parents, names and pages;
`/docs` still renders the handbook alone.

WHEN IT IS SEEDED. `main.startup()` calls `seed()` once, on a FRESH graph (no node at all
before this boot's seeding), under the profiles a new install chooses: `ATLAS_SEED=none`,
`ATLAS_SEED=demo` and `ATLAS_SEED=self`. Never under `homelab`, the code default: that profile's
promise is "exactly today's seed" (STORY-oss-07 criterion 1, pinned by `verify_fresh_install.py`
§A), and the homelab documents itself already, under its own `atlas` project. A populated
database is never seeded at boot, under any profile, so "boot is a read" holds
(`verify_object_graph.py` §15). An existing install that wants the node set runs this module by
hand (below).

IDEMPOTENT, AND IT NEVER TOUCHES WHAT EXISTS. A node whose id is present is skipped, and so are
its documents, its intents and its edges: nothing is updated, renamed or re-parented. An edge is
added only when at least one end was added in this run (or both ends are handbook nodes, which an
install made before the baseload has without the edges between them) and both ends are this
set's own (added in this run, a handbook node, or a node carrying `attributes.baseload`), and
only when it is not there already, so a person's own node
that happens to hold an `atlas-system*` id is never wired in. Every id starts with
`atlas-system`, so it cannot meet a homelab's `atlas`, `atlas-api`, `atlas-mcp`,
`atlas-postgres` or `atlas-retrieval`. Rows are written directly, as `demo_seed.py` writes its
graph: a seed is not a user mutation and records no `graph_event`.

    python system_node.py            # dry run: which ids would be added
    python system_node.py --apply    # add the missing ones (in the image: /app/system_node.py)
"""
from __future__ import annotations

import argparse
import copy
import sys

from sqlalchemy import select
from sqlalchemy.orm import Session

import baseload_data
import system_handbook
from models_auth import VISIBILITY_SHARED, NodeVisibility
from models_graph import Edge, Node, NodeDoc, NodeIntent, NodeType

#: The handbook set (unchanged names: other modules and checks read them).
NODES = system_handbook.NODES
IDS = tuple(n["id"] for n in NODES)
ROOT = system_handbook.ROOT

#: The baseload's own nodes, after the handbook set, parents first.
BASELOAD_NODES = baseload_data.NODES
BASELOAD_IDS = tuple(n["id"] for n in BASELOAD_NODES)
#: Everything this module seeds, in seeding order.
ALL_IDS = IDS + BASELOAD_IDS
#: Every edge of the full set on a fresh graph, as (src, edge_type, dst).
ALL_EDGES = tuple(
    [(n["parent"], "contains", n["id"]) for n in NODES if n["parent"]]
    + [(n["parent"], "contains", n["id"]) for n in BASELOAD_NODES]
    + [(e["src"], e["edge_type"], e["dst"]) for e in baseload_data.EDGES]
)
#: Every intent of the set, as (node_id, slug).
ALL_INTENTS = tuple((i["node_id"], i["slug"]) for i in baseload_data.INTENTS)


def _doc_entry(path: str, d: dict) -> dict:
    return {"path": path, "kind": d["kind"], "title": d["title"], "format": "md"}


def documents(node_id: str) -> list[tuple[str, dict]]:
    """[(node_doc path, doc)] for every document the set gives `node_id` on a fresh graph."""
    for n in NODES:
        if n["id"] == node_id:
            extra = baseload_data.HANDBOOK_EXTRAS.get(node_id, {}).get("docs", [])
            return [(system_handbook.doc_path(node_id, d), d) for d in list(n["docs"]) + list(extra)]
    for n in BASELOAD_NODES:
        if n["id"] == node_id:
            return [(system_handbook.doc_path(node_id, d), d) for d in n["docs"]]
    raise KeyError(node_id)


def missing(s: Session) -> list[str]:
    """The ids of the set that are not in the graph, in seeding order."""
    present = set(s.scalars(select(Node.id).where(Node.id.in_(ALL_IDS))))
    return [i for i in ALL_IDS if i not in present]


def seed(s: Session) -> list[str]:
    """Add every node of the set that is missing, with its documents, intents and edges.

    Returns the ids added (empty: nothing was written, not even a derived value). Assumes the
    node_type and edge_type registries exist (startup seeds them first).
    """
    add = set(missing(s))
    if not add:
        return []
    known_types = set(s.scalars(select(NodeType.id)))
    for n in list(NODES) + list(BASELOAD_NODES):
        if n["id"] in add and n["type"] not in known_types:
            raise RuntimeError(f"system node {n['id']}: node type {n['type']!r} is not registered")
    # Which present ids are this set's own: a handbook node, or one carrying attributes.baseload.
    ours = set(add) | (set(IDS) - add)
    for nid, attrs in s.execute(select(Node.id, Node.attributes).where(
            Node.id.in_([i for i in BASELOAD_IDS if i not in add]))):
        if isinstance(attrs, dict) and "baseload" in attrs:
            ours.add(nid)

    for n in NODES:
        if n["id"] not in add:
            continue
        attrs = {"docs": [_doc_entry(p, d) for p, d in documents(n["id"])]}
        setting = baseload_data.HANDBOOK_EXTRAS.get(n["id"], {}).get("setting")
        if setting:
            attrs["setting"] = setting
        s.add(Node(id=n["id"], type=n["type"], name=n["name"], summary=n["summary"],
                   attributes=attrs, body=None, source=None, origin="atlas"))
    for n in BASELOAD_NODES:
        if n["id"] not in add:
            continue
        attrs = copy.deepcopy(n["attributes"])
        attrs["docs"] = [_doc_entry(p, d) for p, d in documents(n["id"])]
        s.add(Node(id=n["id"], type=n["type"], name=n["name"], summary=n["summary"],
                   abstract=n.get("abstract"), detail=n.get("detail"),
                   attributes=attrs, body=None, source=None, origin="atlas"))
    s.flush()

    for nid in ALL_IDS:
        if nid in add:
            for path, d in documents(nid):
                s.add(NodeDoc(node_id=nid, path=path, content=d["content"]))
    existing = set(s.execute(select(Edge.src, Edge.edge_type, Edge.dst).where(
        Edge.src.in_(ALL_IDS), Edge.dst.in_(ALL_IDS))).all())
    handbook = set(IDS)
    for src, edge_type, dst in ALL_EDGES:
        # New at one end, or between two handbook nodes (an install made before the baseload has
        # those nodes and none of the `requires` edges between them, e.g. atlas-mcp -> atlas-api).
        if (src in add or dst in add or (src in handbook and dst in handbook)) \
                and src in ours and dst in ours and (src, edge_type, dst) not in existing:
            s.add(Edge(src=src, dst=dst, edge_type=edge_type, origin="atlas"))
    position: dict[str, int] = {}
    for it in baseload_data.INTENTS:
        if it["node_id"] not in add:
            continue
        pos = position.get(it["node_id"], 0)
        position[it["node_id"]] = pos + 1
        s.add(NodeIntent(node_id=it["node_id"], slug=it["slug"], kind=it["kind"], title=it["title"],
                         statement=it["statement"], source=None, position=pos))
    # SHARED, explicitly. Under ATLAS_RBAC=projects the root is its own project, and an unmarked
    # project takes ATLAS_DEFAULT_PROJECT_VISIBILITY, which the OSS install sets to `private`:
    # nobody would hold a role on it and the handbook would be invisible to everyone. Marked
    # `shared`, every person reads it at ATLAS_SHARED_PROJECT_ROLE. With RBAC off (the default)
    # a `shared` mark changes nothing: only `private` marks block. A mark that is already there
    # (marks outlive their node, models_auth) is left as it is.
    if ROOT in add and s.get(NodeVisibility, ROOT) is None:
        s.add(NodeVisibility(node_id=ROOT, visibility=VISIBILITY_SHARED, set_by=None))
    s.flush()
    from attention import recompute_derived  # lazy, like the graph handlers
    recompute_derived(s)
    added = [i for i in ALL_IDS if i in add]
    shown = ", ".join(added) if len(added) <= 12 else ", ".join(added[:12]) + f", ... ({len(added) - 12} more)"
    print(f"[atlas] seed: system node set, {len(added)} node(s) added: {shown}")
    return added


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="system_node.py", description=__doc__.split("\n")[0])
    ap.add_argument("--apply", action="store_true", help="write; without it, a dry run")
    args = ap.parse_args(argv)
    from db import session
    with session() as s:
        todo = missing(s)
        if not todo:
            print("system node set: every node is present; nothing to do")
            return 0
        if not args.apply:
            print("system node set: would add " + ", ".join(todo) + " (dry run; --apply writes)")
            return 0
        seed(s)
        s.commit()
    return 0


if __name__ == "__main__":
    sys.exit(main())
